/**
 * Same shape as `en`, but every leaf widened to `string` — so a translation
 * file must supply every key, without having to repeat the English literal.
 */
export type Dictionary = {
  [Section in keyof typeof en]: { [Key in keyof (typeof en)[Section]]: string }
}

export type Section = keyof Dictionary
/** Dotted key, e.g. "nav.home" — checked at compile time. */
export type TranslationKey = {
  [S in Section]: `${S}.${Extract<keyof Dictionary[S], string>}`
}[Section]
